func cleanedRelated(related []string, ownSlug string) []string {
	out := make([]string, 0, len(related))
	for _, r := range related {
		r = strings.TrimSpace(r)
		if r == "" || r == ownSlug {
			continue
		}
		out = append(out, r)
	}
	return out
}

func containsString(haystack []string, needle string) bool {
	for _, s := range haystack {
		if s == needle {
			return true
		}
	}
	return false
}

func displayFilename(src *source.Source) string {
	name := strings.TrimSpace(src.Filename)
	if name == "" {
		return src.ID
	}
	return name
}

// buildPreview extracts the first substantive block from OCR markdown by
// skipping header lines (# Source OCR, Source ID, Model, ## Page 1).
func buildPreview(rawMD string, maxChars int) string {
	if maxChars <= 0 {
		return ""
	}
	lines := strings.Split(rawMD, "\n")
	contentStart := 0
	for i, line := range lines {
		if strings.HasPrefix(strings.TrimSpace(line), "## Page") {
			contentStart = i + 1
			break
		}
	}
	rest := strings.TrimSpace(strings.Join(lines[contentStart:], "\n"))
	if rest == "" {
		return ""
	}
	if len(rest) <= maxChars {
		return rest
	}
	// Cut at a UTF-8 boundary.
	cut := maxChars
	for cut > 0 && (rest[cut]&0xC0) == 0x80 {
		cut--
	}
	return strings.TrimRight(rest[:cut], " \n\t") + "…"
}

func staleSlugsToDelete(prev []string, current string) []string {
	return staleSlugsToDeleteMany(prev, []string{current})
}

func staleSlugsToDeleteMany(prev []string, current []string) []string {
	keep := make(map[string]struct{}, len(current))
	for _, s := range current {
		if s != "" {
			keep[s] = struct{}{}
		}
	}
	out := make([]string, 0, len(prev))
	for _, s := range prev {
		if _, ok := keep[s]; s != "" && !ok {
			out = append(out, s)
		}
	}
	return out
}

func compiledPageNote(slug string, materialized []string, already bool) string {
	prefix := "compiled"
	if already {
		prefix = "already compiled"
	}
	if len(materialized) == 0 {
		return fmt.Sprintf("%s as [[%s]]", prefix, slug)
	}
	return fmt.Sprintf("%s as [[%s]] + %d materialized section pages", prefix, slug, len(materialized))
}

func derivedRelatedSlugs(delta ExtractionDelta, ownSlug string) []string {
	out := make([]string, 0, delta.TotalItems())
	for _, ent := range delta.Entities {
		if ent.Slug != ownSlug {
			out = append(out, ent.Slug)
		}
	}
	for _, c := range delta.Concepts {
		if c.Slug != ownSlug {
			out = append(out, c.Slug)
		}
	}
	return out
}

// shortID returns the first 6 hex chars after the "src_" prefix for use as a
// disambiguation suffix in collision-aware title resolution.
func shortID(sourceID string) string {
	const prefix = "src_"
	if !strings.HasPrefix(sourceID, prefix) {
		return ""
	}
	rest := sourceID[len(prefix):]
	if len(rest) < 6 {
		return rest
	}
	return rest[:6]
}

func pageBelongsTo(page *wiki.Page, sourceID string) bool {
	if page == nil {
		return false
	}
	return containsString(page.Sources, "source:"+sourceID)
}
